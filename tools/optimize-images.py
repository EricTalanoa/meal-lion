"""Make smaller, pixel-identical web copies of the images the game uses.

Usage: python tools/optimize-images.py        (needs Pillow with WebP support: pip install pillow)

Reads every image referenced by assets/asset-map.json (originals stay untouched under
reference/), writes a lossless WebP copy under assets/web/ with the same dimensions, checks
that every visible pixel decodes identically, and records the result in
assets/web/manifest.json. tools/build.cjs publishes these copies instead of the originals
when the manifest's source hash still matches; otherwise it falls back to the original PNG.
Unchanged sources are skipped, so rerunning is cheap. Free and offline; no paid service.
"""
import hashlib
import io
import json
import pathlib
import sys

from PIL import Image, ImageChops, features

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'web'
MANIFEST = OUT / 'manifest.json'


def mapped_files():
    m = json.loads((ROOT / 'assets' / 'asset-map.json').read_text(encoding='utf-8'))
    items = [m['background'], m['chef'], *m['meals'], *m['ingredients'], *m['animations']]
    return sorted({x['file'] for x in items})


def visible(im):
    """RGBA with fully transparent pixels zeroed: their colour never reaches the screen."""
    im = im.convert('RGBA')
    alpha = im.getchannel('A')
    clear = Image.new('RGBA', im.size, (0, 0, 0, 0))
    return Image.composite(im, clear, alpha.point(lambda a: 255 if a else 0))


def main():
    if not features.check('webp'):
        sys.exit('Pillow was built without WebP support')
    old = json.loads(MANIFEST.read_text(encoding='utf-8'))['files'] if MANIFEST.exists() else {}
    files = {}
    for rel in mapped_files():
        src = ROOT / rel
        data = src.read_bytes()
        sha = hashlib.sha256(data).hexdigest()
        dest_rel = 'assets/web/' + rel.removeprefix('reference/').rsplit('.', 1)[0] + '.webp'
        dest = ROOT / dest_rel
        prev = old.get(rel)
        if prev and prev['sourceSha256'] == sha and prev['file'] == dest_rel and dest.exists():
            files[rel] = prev
            print(f'unchanged {rel}')
            continue
        im = Image.open(io.BytesIO(data))
        im.load()
        buf = io.BytesIO()
        # method 6 = slowest/smallest; exact=False lets the encoder rewrite invisible pixels.
        im.save(buf, 'WEBP', lossless=True, quality=100, method=6, exact=False)
        out = Image.open(io.BytesIO(buf.getvalue()))
        out.load()
        if out.size != im.size or ImageChops.difference(visible(im), visible(out)).getbbox():
            sys.exit(f'Lossless check failed for {rel}')
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(buf.getvalue())
        files[rel] = {'file': dest_rel, 'sourceSha256': sha, 'sourceBytes': len(data),
                      'bytes': len(buf.getvalue()), 'width': im.width, 'height': im.height}
        print(f'{rel}: {len(data):,} -> {len(buf.getvalue()):,} bytes')
    MANIFEST.write_text(json.dumps({
        'note': 'Generated by tools/optimize-images.py. Lossless WebP copies of reference/ art; '
                'same dimensions and visible pixels. Do not edit by hand.',
        'files': files}, indent=2) + '\n', encoding='utf-8')
    before = sum(f['sourceBytes'] for f in files.values())
    after = sum(f['bytes'] for f in files.values())
    print(f'Total {before:,} -> {after:,} bytes ({after / before:.0%})')


if __name__ == '__main__':
    main()
