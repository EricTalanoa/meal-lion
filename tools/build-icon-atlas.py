"""Pack every ingredient icon into one small sheet the game loads at startup.

Usage: python tools/build-icon-atlas.py        (needs Pillow with WebP support)

The source icons are 1-2 MB sheets or ~1250 px single images, but the game never draws an
icon larger than a 96 px canvas. Loading them one by one on first reveal made a lettered
placeholder flash before the picture arrived. This writes assets/web/icon-atlas.webp (one
96 px cell per ingredient label, aspect ratio kept, centred) and assets/web/icon-atlas.json.
tools/build.cjs publishes the sheet only while the JSON's inputSha256 still matches the
current asset map and source files; otherwise the game falls back to the per-file icons.
Originals stay untouched. Free and offline; no paid service.
"""
import hashlib
import io
import json
import math
import pathlib
import sys

from PIL import Image, features

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'web'
CELL = 96
COLUMNS = 10


def chosen_icons(m):
    """One icon per label, chosen exactly like game/art.mjs: first entry, unless a later one is preferred."""
    icons = {}
    for item in m['ingredients']:
        if item['label'] not in icons or item.get('preferred'):
            icons[item['label']] = item
    return icons


def input_sha(icons):
    """Same digest as inputSha256() in tools/build.cjs."""
    hashes = {}
    lines = []
    for label, it in icons.items():
        f = it['file']
        if f not in hashes:
            hashes[f] = hashlib.sha256((ROOT / f).read_bytes()).hexdigest()
        lines.append('|'.join([label, f, str(it['columns']), str(it['rows']), str(it['index']), hashes[f]]))
    return hashlib.sha256('\n'.join(lines).encode('utf-8')).hexdigest()


def main():
    if not features.check('webp'):
        sys.exit('Pillow was built without WebP support')
    m = json.loads((ROOT / 'assets' / 'asset-map.json').read_text(encoding='utf-8'))
    icons = chosen_icons(m)
    labels = list(icons)
    rows = math.ceil(len(labels) / COLUMNS)
    sheet = Image.new('RGBA', (COLUMNS * CELL, rows * CELL), (0, 0, 0, 0))
    opened = {}
    for i, label in enumerate(labels):
        it = icons[label]
        if it['file'] not in opened:
            opened[it['file']] = Image.open(ROOT / it['file']).convert('RGBA')
        src = opened[it['file']]
        sw, sh = src.width / it['columns'], src.height / it['rows']
        x, y = (it['index'] % it['columns']) * sw, (it['index'] // it['columns']) * sh
        cell = src.crop((round(x), round(y), round(x + sw), round(y + sh)))
        scale = CELL / max(cell.size)
        size = (max(1, round(cell.width * scale)), max(1, round(cell.height * scale)))
        # Pillow premultiplies alpha when resampling RGBA, so edges don't pick up fringe colour.
        cell = cell.resize(size, Image.LANCZOS)
        sheet.alpha_composite(cell, ((i % COLUMNS) * CELL + (CELL - size[0]) // 2, (i // COLUMNS) * CELL + (CELL - size[1]) // 2))
    buf = io.BytesIO()
    sheet.save(buf, 'WEBP', quality=90, alpha_quality=100, method=6)
    (OUT / 'icon-atlas.webp').write_bytes(buf.getvalue())
    (OUT / 'icon-atlas.json').write_text(json.dumps({
        'note': 'Generated by tools/build-icon-atlas.py. Do not edit by hand.',
        'file': 'assets/web/icon-atlas.webp', 'cell': CELL, 'columns': COLUMNS,
        'inputSha256': input_sha(icons), 'labels': labels}, indent=2) + '\n', encoding='utf-8')
    print(f'{len(labels)} icons -> {sheet.width}x{sheet.height}, {len(buf.getvalue()):,} bytes')


if __name__ == '__main__':
    main()
