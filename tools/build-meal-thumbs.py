"""Make a small copy of each finished-meal picture for the result screen.

Usage: python tools/build-meal-thumbs.py        (needs Pillow with WebP support)
tools/optimize-images.py runs this automatically.

The meal sources are 0.5-1.1 MB sheets or single images, but the game draws a meal at most
240 px (the result plate canvas). Fetching the full file when a round ended made the plate
appear a moment after the result. This writes assets/web/meals/meal-<id>.webp (the meal's cell,
aspect ratio kept, centred in 240x240) and assets/web/meals/meals.json. Each entry records a
key over its source cell and file hash; tools/build.cjs publishes a copy only while its key
still matches the asset map, otherwise that meal falls back to its full-size image.
Originals stay untouched. Free and offline; no paid service.
"""
import hashlib
import io
import json
import pathlib
import sys

from PIL import Image, features

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'web' / 'meals'
SIZE = 240


def key(item, file_sha):
    """Same digest as mealKey() in tools/build.cjs."""
    text = '|'.join([item['file'], str(item['columns']), str(item['rows']), str(item['index']), file_sha])
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def main():
    if not features.check('webp'):
        sys.exit('Pillow was built without WebP support')
    m = json.loads((ROOT / 'assets' / 'asset-map.json').read_text(encoding='utf-8'))
    OUT.mkdir(parents=True, exist_ok=True)
    opened, hashes, meals, total = {}, {}, {}, 0
    for item in m['meals']:
        f = item['file']
        if f not in opened:
            opened[f] = Image.open(ROOT / f).convert('RGBA')
            hashes[f] = hashlib.sha256((ROOT / f).read_bytes()).hexdigest()
        src = opened[f]
        sw, sh = src.width / item['columns'], src.height / item['rows']
        x, y = (item['index'] % item['columns']) * sw, (item['index'] // item['columns']) * sh
        cell = src.crop((round(x), round(y), round(x + sw), round(y + sh)))
        scale = SIZE / max(cell.size)
        size = (max(1, round(cell.width * scale)), max(1, round(cell.height * scale)))
        out = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0))
        # Pillow premultiplies alpha when resampling RGBA, so edges don't pick up fringe colour.
        out.alpha_composite(cell.resize(size, Image.LANCZOS), ((SIZE - size[0]) // 2, (SIZE - size[1]) // 2))
        buf = io.BytesIO()
        out.save(buf, 'WEBP', quality=90, alpha_quality=100, method=6)
        rel = f'assets/web/meals/meal-{item["id"]}.webp'
        (ROOT / rel).write_bytes(buf.getvalue())
        meals[str(item['id'])] = {'file': rel, 'key': key(item, hashes[f])}
        total += len(buf.getvalue())
    (OUT / 'meals.json').write_text(json.dumps({
        'note': 'Generated by tools/build-meal-thumbs.py. Do not edit by hand.',
        'size': SIZE, 'meals': meals}, indent=2) + '\n', encoding='utf-8')
    print(f'{len(meals)} meals -> {SIZE}px copies, {total:,} bytes total')


if __name__ == '__main__':
    main()
